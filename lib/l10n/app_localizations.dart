enum AppLanguage {
  system('system', 'پیش‌فرض سیستم', 'System Default'),
  fa('fa', 'فارسی', 'Persian'),
  en('en', 'English', 'English'),
  ar('ar', 'العربية', 'Arabic'),
  zh('zh', '中文', 'Chinese'),
  ru('ru', 'Русский', 'Russian'),
  es('es', 'Español', 'Spanish'),
  it('it', 'Italiano', 'Italian'),
  de('de', 'Deutsch', 'German'),
  fr('fr', 'Français', 'French'),
  hi('hi', 'हिन्दी', 'Hindi');

  final String code;
  final String nativeName;
  final String englishName;

  const AppLanguage(this.code, this.nativeName, this.englishName);

  String get displayName =>
      this == AppLanguage.system ? nativeName : '$nativeName ($englishName)';

  static AppLanguage fromCode(String? code) {
    if (code == null) return AppLanguage.system;
    for (final l in values) {
      if (l.code == code) return l;
    }
    return AppLanguage.system;
  }

  Locale? get locale {
    if (this == AppLanguage.system) return null;
    return Locale(code);
  }

  bool get isRtl => code == 'fa' || code == 'ar';
}

